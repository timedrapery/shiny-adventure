def render_guide(guide: dict[str, object], glossary: dict[str, str]) -> list[str]:
    labels = (
        ("What happens", "scene"),
        ("Central question", "question"),
        ("Main point", "main_point"),
        ("Reading tip", "reading_cue"),
        ("This text is not saying", "not_saying"),
    )
    lines = ['<div class="reader-guide" markdown="1">', ""]
    for label, field in labels:
        lines.extend([f"### {label}", "", str(guide[field]).strip(), ""])
    lines.extend(["### Key words", "", '<dl class="reader-guide__terms">'])
    for requested in guide["key_terms"]:  # type: ignore[union-attr]
        term, gloss = glossary_entry(str(requested), glossary)
        lines.append(f"<dt><dfn>{html.escape(term)}</dfn></dt>")
        lines.append(f"<dd>{html.escape(gloss)}</dd>")
    lines.extend(["</dl>", "", "</div>"])
    return lines


def render_terms_panel(entries: list[tuple[str, str]]) -> list[str]:
    count = len(entries)
    noun = "word" if count == 1 else "words"
    lines = [
        '<details class="reader-terms">',
        f"<summary>{noun.capitalize()} used in this translation ({count})</summary>",
        "<dl>",
    ]
    for term, gloss in entries:
        lines.append(f"<dt><dfn>{html.escape(term)}</dfn></dt>")
        lines.append(f"<dd>{html.escape(gloss)}</dd>")
    lines.extend(["</dl>", "</details>"])
    return lines


def render_reading_nav(
    previous: TranslationSurface | None,
    following: TranslationSurface | None,
) -> list[str]:
    items: list[tuple[str, str]] = []
    if previous is not None:
        items.append((previous.main_name, f"← {display_title(previous)}"))
    items.append(("index.md", "All suttas"))
    if following is not None:
        items.append((following.main_name, f"{display_title(following)} →"))
    # Keep Markdown links inside a semantic nav so MkDocs rewrites source .md
    # targets into the correct directory URLs for the built site.
    lines = [
        '<nav class="reading-order" aria-label="Reading order" markdown="1">',
        "",
    ]
    for target, label in items:
        lines.append(f"- [{label}]({target})")
    lines.extend(["", "</nav>"])
    return lines

def render_sutta_page(
    surface: TranslationSurface,
    intro: str | None,
    glossary: dict[str, str],
    previous: TranslationSurface | None,
    following: TranslationSurface | None,
    guide: dict[str, object] | None = None,
) -> str:
    meta = reader_meta(surface)
    body = surface_body(surface.main_path.read_text(encoding="utf-8"))
    words, minutes = reading_stats(body)
    stage_name = dict((n, t) for n, t, _ in STAGES)[meta.stage]

    lines = [
        GENERATED_BANNER,
        "",
        f"# {display_title(surface)}",
        "",
        f"*{surface.label}, the {meta.pali_title} — "
        f"set {meta.stage}, {stage_name}*",
        "",
        f'<p class="reading-meta"><strong>Reading time:</strong> about {minutes} min '
        f"· {words:,} words</p>",
        "",
        "[Skip to the translation](#translation){ .reader-skip-link }",
        "",
        "## Before you read",
        "",
    ]
    entries = glossary_for_page(body, glossary)
    abbreviations = glossary_abbreviations_for_page(body, glossary)
    if guide is not None:
        lines.extend(render_guide(guide, glossary))
    else:
        lines.append(intro.strip() if intro else DEFAULT_INTRO)
    lines.extend(["", "## Translation", "", body, ""])
    lines.extend(render_terms_panel(entries))
    lines.extend(["", "---", ""])
    lines.extend(render_reading_nav(previous, following))
    lines.append("")

    # Keep inline abbreviation definitions as a convenience for pointer users.
    # The visible terms panel above is the accessible, input-independent route.
    if abbreviations:
        lines.append("")
        for term, gloss in abbreviations:
            lines.append(f"*[{term}]: {gloss}")
    return "\n".join(lines).rstrip() + "\n"


def render_home() -> str:
    total = len(TRANSLATION_SURFACES)
    by_key = {s.key: s for s in TRANSLATION_SURFACES}
    essential_words = 0
    for key in ESSENTIAL_FIVE:
        body = surface_body(by_key[key].main_path.read_text(encoding="utf-8"))
        essential_words += translation_word_count(body)
    essential_minutes = max(1, math.ceil(essential_words / WORDS_PER_MINUTE))
    lines = [
        "# OSF Pali Readings",
        "",
        "Early Buddhist discourses in plain, contemporary English.",
        "",
        f"All {total} translations in this collection are readable here. Each "
        "one is backed by a governed Pali lexicon, so a term that matters is "
        "translated the same way every time it appears, and every translation "
        "decision has a written reason behind it. See "
        "[About this translation](about.md) for what that means in practice.",
        "",
        "## Start reading",
        "",
        "- [**Start Here**](start-here.md) — a newcomer-friendly reading order "
        f"through all {total} texts, arranged by what makes sense to read "
        "first rather than by editorial priority",
        "- [**All Suttas**](suttas/index.md) — the full collection, if you "
        "already know what you are looking for",
        "- [**Glossary**](glossary.md) — the recurring vocabulary, in plain "
        "English",
        # Deliberately a raw anchor rather than a Markdown link. The book is
        # built by scripts/build_book.py straight into the built site, after
        # MkDocs has run, so it is not among the source files MkDocs knows
        # about. A Markdown link here would fail `mkdocs build --strict` for
        # anyone building the site without pandoc installed, which is most
        # people editing a translation.
        '- <a href="downloads/osf-pali-readings.epub"><strong>Download the '
        "whole collection</strong></a> — EPUB, for e-readers, phones, and "
        "reading offline",
        "",
        "## If you only read five",
        "",
        "Together these give a compact first route through the collection: "
        f"about {essential_minutes} minutes of reading ({essential_words:,} words).",
        "",
    ]
    for key in ESSENTIAL_FIVE:
        surface = by_key[key]
        meta = reader_meta(surface)
        lines.append(
            f"- [**{display_title(surface)}**](suttas/{surface.main_name}) — "
            f"{surface.label}, {meta.pali_title}"
        )
    lines.extend([
        "",
        "## How to read these",
        "",
        "The translations use clear, common English. Each page gives a reading "
        "time and a short orientation before the governed translation. Where a "
        "word is doing technical work, open the words-used panel for a plain-"
        "English definition. Some browsers also show the same note when you "
        "point to a marked word.",
        "",
        "Repetition has been kept where the texts repeat. These were spoken "
        "and memorised, and the repeating is part of how they work.",
    ])
    return "\n".join(lines).rstrip() + "\n"


def render_start_here() -> str:
    lines = [
        "# Start Here",
        "",
        f"A suggested order for reading the {len(TRANSLATION_SURFACES)} "
        "translations in this collection, for someone new to this material.",
        "",
        "This is deliberately **not** the project's internal translation "
        "roadmap. That roadmap ranks texts by editorial leverage — which "
        "translation next does the most to strengthen the lexicon. This page "
        "ranks the same texts by a different question: if you have never read "
        "early Buddhist material, what order actually makes sense? The two "
        "orderings often disagree, and that is expected.",
        "",
        "Every text below is readable on this site.",
        "",
    ]
    for number, title, blurb in STAGES:
        staged = [
            s for s in surfaces_in_reading_order()
            if reader_meta(s).stage == number
        ]
        lines.extend([f"## Set {number} — {title}", "", blurb, ""])
        for surface in staged:
            meta = reader_meta(surface)
            label = display_title(surface)
            suffix = f" ({surface.label}, {meta.pali_title})"
            lines.append(
                f"- [**{label}**](suttas/{surface.main_name}){suffix} — "
                f"{meta.path_note}"
            )
        lines.append("")

    by_key = {s.key: s for s in TRANSLATION_SURFACES}
    names = ", ".join(
        f"[{display_title(by_key[k])}](suttas/{by_key[k].main_name})"
        for k in ESSENTIAL_FIVE
    )
    lines.extend([
        "## If you only read five",
        "",
        f"{names}. Together they introduce how to test a teaching, which "
        "questions help practice, the basic diagnosis and path, the difference "
        "between pain and added suffering, and the examination of self.",
    ])
    return "\n".join(lines).rstrip() + "\n"


def render_all_suttas() -> str:
    lines = [
        "# All Suttas",
        "",
        f"All {len(TRANSLATION_SURFACES)} translations, grouped by collection. "
        "If you would rather be guided, use [Start Here](../start-here.md).",
        "",
    ]
    collections = [
        ("DN", "Dīgha Nikāya", "the long discourses"),
        ("MN", "Majjhima Nikāya", "the middle-length discourses"),
        ("SN", "Saṁyutta Nikāya", "the connected discourses"),
        ("AN", "Aṅguttara Nikāya", "the numbered discourses"),
        ("Iti", "Itivuttaka", "the short sayings, in the Khuddaka Nikāya"),
    ]

    def sort_key(surface: TranslationSurface) -> tuple[int, int]:
        numbers = re.findall(r"\d+", surface.label)
        major = int(numbers[0]) if numbers else 0
        minor = int(numbers[1]) if len(numbers) > 1 else 0
        return major, minor

    for prefix, pali, gloss in collections:
        group = sorted(
            (s for s in TRANSLATION_SURFACES if s.label.startswith(prefix + " ")),
            key=sort_key,
        )
        if not group:
            continue
        lines.extend([f"## {pali} ({prefix}) — {gloss}", ""])
        for surface in group:
            meta = reader_meta(surface)
            note = meta.path_note.split(".")[0].strip() + "."
            lines.append(
                f"- [**{display_title(surface)}**]({surface.main_name}) — "
                f"{surface.label} · {meta.pali_title} · Set {meta.stage}. {note}"
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_glossary() -> str:
    glossary = load_glossary()
    records = load_term_records()

    by_rendering: dict[str, dict[str, object]] = {}
    for record in records:
        preferred = record.get("preferred_translation")
        if isinstance(preferred, str):
            by_rendering.setdefault(preferred.casefold(), record)

    lines = [
        "# Glossary",
        "",
        "The recurring vocabulary of these translations, in plain English.",
        "",
        "Every term here is governed: the project fixes one English rendering "
        "for each Pali term and uses it consistently, so that a word carrying "
        "technical weight does not quietly change meaning between texts. The "
        "explanations below are written for readers. The editorial reasoning "
        "behind each choice lives in the "
        "[repository](https://github.com/timedrapery/shiny-adventure/tree/main/terms).",
        "",
        "Each sutta also has a visible words-used panel. Some browsers show the "
        "same definitions on marked terms, but the panel works without hovering.",
        "",
        '<dl class="glossary-list">',
    ]
    seen_definitions: set[tuple[str, str]] = set()
    for term, gloss in sorted(glossary.items(), key=lambda kv: kv[0].casefold()):
        identity = (term.casefold(), gloss)
        if identity in seen_definitions:
            continue
        seen_definitions.add(identity)
        record = by_rendering.get(term.casefold())
        pali = ""
        if record is not None and isinstance(record.get("term"), str):
            pali = str(record["term"])
        pali_note = (
            f' <span class="glossary-pali" lang="pi">({html.escape(pali)})</span>'
            if pali else ""
        )
        lines.append(f"<dt><dfn>{html.escape(term)}</dfn>{pali_note}</dt>")
        lines.append(f"<dd>{html.escape(gloss)}</dd>")

    lines.extend([
        "</dl>",
        "",
        "## Terms deliberately left in Pali",
        "",
        "A few words are kept in Pali because every English option narrows "
        "them misleadingly. Where that is the case, the surrounding text is "
        "written so the sense is still followable.",
        "",
        "`bhikkhu`, `dhamma`, `nibbāna`, and `Tathāgata` are the main ones.",
    ])
    return "\n".join(lines).rstrip() + "\n"


def render_nav() -> str:
    lines = []
    for number, title, _ in STAGES:
        staged = [
            s for s in surfaces_in_reading_order()
            if reader_meta(s).stage == number
        ]
        if not staged:
            continue
        lines.append(f"      - Set {number}. {title}:")
        for surface in staged:
            label = display_title(surface).replace('"', "'")
            lines.append(f'          - "{label}": suttas/{surface.main_name}')
    return "\n".join(lines)


