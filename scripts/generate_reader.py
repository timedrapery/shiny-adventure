def load_glossary() -> dict[str, str]:
    """Reader-facing term glosses, keyed by the English surface string.

    The source is `includes/glossary.md`, whose definitions are written for
    non-specialist readers. It is deliberately not the editorial `notes` field from the
    term records, which is written for contributors.
    """
    if not GLOSSARY_SOURCE.exists():
        return {}
    entries: dict[str, str] = {}
    for line in GLOSSARY_SOURCE.read_text(encoding="utf-8").splitlines():
        match = re.match(r"^\*\[([^\]]+)\]:\s*(.+)$", line.strip())
        if match:
            entries[match.group(1)] = match.group(2).strip()
    return entries


def glossary_abbreviations_for_page(
    body: str,
    glossary: dict[str, str],
) -> list[tuple[str, str]]:
    """Exact-case definitions that can become inline abbreviation notes."""
    return [
        (term, gloss)
        for term, gloss in sorted(glossary.items(), key=lambda item: item[0].casefold())
        if re.search(rf"(?<!\w){re.escape(term)}(?!\w)", body)
    ]


def glossary_for_page(body: str, glossary: dict[str, str]) -> list[tuple[str, str]]:
    """Visible glossary entries whose term actually appears on this page.

    Injecting per page rather than appending the whole glossary to every page
    is what makes a term able to carry a different note in a different sutta:
    the definition now travels with the page instead of being global.

    Exact capitalization remains meaningful where it carries a different
    gloss (`Dhamma` and `dhamma`). Case variants with the same definition are
    collapsed for the visible list, while inline abbreviations stay exact-case.
    """
    exact = glossary_abbreviations_for_page(body, glossary)
    exact_folded_terms = {term.casefold() for term, _ in exact}
    found: list[tuple[str, str]] = []
    seen: set[tuple[str, str]] = set()
    for term, gloss in exact:
        identity = (term.casefold(), gloss)
        if identity not in seen:
            found.append((term, gloss))
            seen.add(identity)

    # A sentence-initial capitalization may not have its own glossary entry.
    # Add a case-insensitive fallback only for definitions not already shown.
    for term, gloss in sorted(glossary.items(), key=lambda item: item[0].casefold()):
        if term.casefold() in exact_folded_terms:
            continue
        identity = (term.casefold(), gloss)
        if identity in seen:
            continue
        if re.search(rf"(?<!\w){re.escape(term)}(?!\w)", body, flags=re.I):
            found.append((term, gloss))
            seen.add(identity)
    return sorted(found, key=lambda item: item[0].casefold())


def glossary_entry(term: str, glossary: dict[str, str]) -> tuple[str, str]:
    """Resolve a guide term without making capitalization a second concept."""
    matches = [(key, value) for key, value in glossary.items()
               if key.casefold() == term.casefold()]
    if not matches:
        raise ValueError(f"newcomer guide uses unknown glossary term {term!r}")
    return matches[0]


GUIDE_TEXT_FIELDS = (
    "scene", "question", "main_point", "reading_cue", "not_saying",
)


def load_newcomer_guides(
    glossary: dict[str, str] | None = None,
) -> dict[str, dict[str, object]]:
    """Load and validate the structured newcomer guides.

    Evidence headings and key terms are checked against the governed corpus so
    an orientation note cannot silently drift away from the text it describes.
    """
    glossary = glossary if glossary is not None else load_glossary()
    surfaces = {surface.key: surface for surface in TRANSLATION_SURFACES}
    guides: dict[str, dict[str, object]] = {}
    if not GUIDES_DIR.exists():
        raise ValueError("includes/newcomer-guides is missing")
    for path in sorted(GUIDES_DIR.glob("*.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError) as error:
            raise ValueError(f"{path.name}: cannot load guide: {error}") from error
        if not isinstance(data, dict):
            raise ValueError(f"{path.name}: guide must be a JSON object")
        key = data.get("surface_key")
        if not isinstance(key, str) or not key:
            raise ValueError(f"{path.name}: surface_key must be a nonempty string")
        if path.stem != key:
            raise ValueError(f"{path.name}: filename and surface_key disagree")
        if key not in surfaces:
            raise ValueError(f"{path.name}: surface_key is not registered")
        if key not in ESSENTIAL_FIVE:
            raise ValueError(f"{path.name}: guides are currently limited to Essential Five")
        if key in guides:
            raise ValueError(f"{path.name}: duplicate guide for {key}")
        for field in GUIDE_TEXT_FIELDS:
            if not isinstance(data.get(field), str) or not str(data[field]).strip():
                raise ValueError(f"{path.name}: {field} must be a nonempty string")
        key_terms = data.get("key_terms")
        if (not isinstance(key_terms, list) or not 3 <= len(key_terms) <= 6
                or any(not isinstance(term, str) or not term.strip()
                       for term in key_terms)):
            raise ValueError(f"{path.name}: key_terms must contain 3 to 6 terms")
        evidence = data.get("evidence_sections")
        if (not isinstance(evidence, list) or not evidence
                or any(not isinstance(heading, str) or not heading.strip()
                       for heading in evidence)):
            raise ValueError(f"{path.name}: evidence_sections must be nonempty strings")
        body = surface_body(surfaces[key].main_path.read_text(encoding="utf-8"))
        headings = set(re.findall(r"^###\s+(.+?)\s*$", body, flags=re.M))
        for heading in evidence:
            if heading not in headings:
                raise ValueError(
                    f"{path.name}: evidence section {heading!r} is not a governed heading"
                )
        for term in key_terms:
            glossary_entry(term, glossary)
            if not re.search(rf"(?<!\w){re.escape(term)}(?!\w)", body, flags=re.I):
                raise ValueError(f"{path.name}: key term {term!r} is absent from the text")
        guides[key] = data
    missing = set(ESSENTIAL_FIVE) - set(guides)
    if missing:
        raise ValueError(
            "newcomer guides missing for Essential Five: " + ", ".join(sorted(missing))
        )
    return guides


def load_term_records() -> list[dict[str, object]]:
    records: list[dict[str, object]] = []
    if not TERMS_DIR.exists():
        return records
    for path in sorted(TERMS_DIR.rglob("*.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError):
            continue
        if isinstance(data, dict):
            records.append(data)
    return records


