def check() -> list[str]:
    problems: list[str] = []
    for path, expected in planned_files().items():
        relative = path.relative_to(REPO_ROOT).as_posix()
        if not path.exists():
            problems.append(f"{relative}: missing")
            continue
        actual = path.read_text(encoding="utf-8")
        if actual != expected:
            diff = list(difflib.unified_diff(
                actual.splitlines(), expected.splitlines(),
                lineterm="", n=1,
            ))[:8]
            problems.append(f"{relative}: stale\n    " + "\n    ".join(diff))
    try:
        if MKDOCS.read_text(encoding="utf-8") != planned_mkdocs():
            problems.append("mkdocs.yml: generated sutta nav is stale")
    except ValueError as error:
        problems.append(f"mkdocs.yml: {error}")
    for path in orphan_pages():
        problems.append(
            f"{path.relative_to(REPO_ROOT).as_posix()}: no registered surface"
        )
    return problems


def write() -> list[str]:
    written: list[str] = []
    SUTTA_DIR.mkdir(parents=True, exist_ok=True)
    for path, content in planned_files().items():
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        path.write_text(content, encoding="utf-8", newline="\n")
        written.append(path.relative_to(REPO_ROOT).as_posix())
    nav = planned_mkdocs()
    if MKDOCS.read_text(encoding="utf-8") != nav:
        MKDOCS.write_text(nav, encoding="utf-8", newline="\n")
        written.append("mkdocs.yml")
    return written


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="Fail if the reader is out of date.")
    parser.add_argument("--write", action="store_true",
                        help="Regenerate the reader.")
    args = parser.parse_args()

    if args.write:
        written = write()
        if written:
            for path in written:
                print(f"wrote {path}")
        else:
            print("Reader already up to date.")
        return 0

    problems = check()
    if not problems:
        print(
            f"Reader is current ({len(TRANSLATION_SURFACES)} surfaces, "
            f"{len(planned_files())} generated files)."
        )
        return 0
    print("Reader is out of date:")
    for problem in problems:
        print(f"- {problem}")
    print("")
    print("Run `python scripts/generate_reader.py --write` to regenerate.")
    return 1 if args.check else 0


if __name__ == "__main__":
    sys.exit(main())
