#!/usr/bin/env python3
"""Generate the reader's edition from the governed translation corpus.

The reader is a presentation layer, never a second source of truth. Everything
it shows about a sutta comes from two places:

  docs/translations/<surface>.md   the canonical governed translation
  scripts/surface_registry.py      reader metadata (title, stage, path note)

and two reader-facing sources:

  includes/newcomer-guides/<surface>.json  structured orientation for the
                                         Essential Five
  the legacy "About this text" / "Before you read" block inside each other
  reader page, which is preserved across regeneration

Everything else -- the page title, the reference line, the translation body,
the reading-path navigation, the per-page glossary, the All Suttas index, the
Start Here path, the home page, the glossary page, and the site navigation --
is generated from those sources and is safe to regenerate at any time.

Usage:

    python scripts/generate_reader.py --check   verify the reader is current
    python scripts/generate_reader.py --write   regenerate it

`--check` is part of `run_checks.py`, so a reader that has drifted from the
governed corpus fails the build rather than going out stale.
"""

