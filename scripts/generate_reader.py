def planned_files() -> dict[Path, str]:
    """Every file the generator owns, mapped to its intended content."""
    glossary = load_glossary()
    guides = load_newcomer_guides(glossary)
    ordered = surfaces_in_reading_order()
    planned: dict[Path, str] = {
        READER_DIR / "index.md": render_home(),
        READER_DIR / "start-here.md": render_start_here(),
        READER_DIR / "glossary.md": render_glossary(),
        SUTTA_DIR / "index.md": render_all_suttas(),
    }
    for position, surface in enumerate(ordered):
        page = SUTTA_DIR / surface.main_name
        planned[page] = render_sutta_page(
            surface,
            existing_intro(page),
            glossary,
            ordered[position - 1] if position else None,
            ordered[position + 1] if position + 1 < len(ordered) else None,
            guides.get(surface.key),
        )
    return planned


def planned_mkdocs() -> str:
    text = MKDOCS.read_text(encoding="utf-8")
    if NAV_BEGIN not in text or NAV_END not in text:
        raise ValueError("mkdocs.yml is missing the generated nav markers")
    head, rest = text.split(NAV_BEGIN, 1)
    _, tail = rest.split(NAV_END, 1)
    return f"{head}{NAV_BEGIN}\n{render_nav()}\n{NAV_END}{tail}"


def orphan_pages() -> list[Path]:
    known = {s.main_name for s in TRANSLATION_SURFACES} | {"index.md"}
    if not SUTTA_DIR.exists():
        return []
    return [p for p in sorted(SUTTA_DIR.glob("*.md")) if p.name not in known]


